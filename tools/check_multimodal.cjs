/* Prueba E2E contra servidor local. Playwright solo se usa para QA, no para servir. */
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const fs=require('node:fs');
(async()=>{
  fs.mkdirSync('output/qa/p2',{recursive:true});
  fs.mkdirSync('docs/images',{recursive:true});
  const browser=await chromium.launch({executablePath:process.env.CHROME_PATH,headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.BD2_URL||'http://127.0.0.1:8000');
  await page.locator('.product-card').first().waitFor();
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('.product-card img')).slice(0,3).every(img=>img.complete&&img.naturalWidth));
  await page.screenshot({path:'output/qa/p2/catalog.png',fullPage:true});
  await page.screenshot({path:'docs/images/catalog.png',fullPage:false});
  if(await page.locator('.product-card').count()!==12)throw Error('Catálogo incompleto');
  await page.locator('#search').fill('blue shirt');
  await page.locator('#search-button').click();
  await page.waitForFunction(()=>!document.body.classList.contains('loading'));
  if(await page.locator('.product-card').count()<1)throw Error('Búsqueda textual vacía');
  if(!await page.locator('#pipeline').innerText().then(s=>s.includes('TFIDF')))throw Error('Falta plan textual');
  await page.locator('.similar-button').first().click();
  await page.waitForFunction(()=>!document.body.classList.contains('loading'));
  if(!await page.locator('#pipeline').innerText().then(s=>s.includes('IVF')))throw Error('Falta IVF real');
  await page.screenshot({path:'output/qa/p2/visual.png',fullPage:true});
  await page.locator('#mode').selectOption('bovw');
  await page.waitForFunction(()=>!document.body.classList.contains('loading'));
  if(!await page.locator('#pipeline').innerText().then(s=>s.includes('BoVW')))throw Error('Falta BoVW real');
  await page.locator('#mode').selectOption('exact');
  await page.waitForFunction(()=>!document.body.classList.contains('loading'));
  if(!await page.locator('#pipeline').innerText().then(s=>s.includes('ExactVectorScan')))throw Error('Falta escaneo exacto');
  const uploadResponse=await page.request.get(new URL('/api/multimodal/image/15970',page.url()).href);
  await page.locator('#image-upload').setInputFiles({name:'consulta-real.jpg',mimeType:'image/jpeg',buffer:await uploadResponse.body()});
  await page.waitForFunction(()=>!document.body.classList.contains('loading'));
  if(await page.locator('.product-card').count()!==12)throw Error('Carga de imagen sin resultados');
  await page.locator('[data-view=map]').click();
  await page.locator('.leaflet-container').waitFor();
  await page.locator('#nearby').check();
  await page.waitForFunction(()=>!document.body.classList.contains('loading'));
  await page.screenshot({path:'output/qa/p2/map.png',fullPage:true});
  await page.locator('#mode').selectOption('spatial_knn');
  await page.waitForFunction(()=>!document.body.classList.contains('loading'));
  if(!await page.locator('#pipeline').innerText().then(s=>s.includes('RTreeKNN')))throw Error('Falta k-NN geográfico');
  await page.locator('[data-view=sql]').click();
  await page.locator('#run-sql').click();
  await page.waitForFunction(()=>!document.getElementById('run-sql').disabled);
  if(await page.locator('#sql-table tbody tr').count()!==10)throw Error('SQL textual incorrecto');
  await page.locator('#sql-example').selectOption('spatial');
  await page.locator('#run-sql').click();
  await page.waitForFunction(()=>!document.getElementById('run-sql').disabled);
  if(await page.locator('#sql-table tbody tr').count()<1)throw Error('SQL espacial vacío');
  await page.screenshot({path:'output/qa/p2/sql.png',fullPage:true});
  await page.locator('[data-view=benchmarks]').click();
  await page.locator('.benchmark-card').first().waitFor();
  if(await page.locator('.benchmark-card').count()!==4)throw Error('Faltan experimentos');
  await page.locator('[data-view=explore]').click();
  await page.locator('#clear-reference').click();
  await page.waitForFunction(()=>!document.body.classList.contains('loading'));
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'output/qa/p2/mobile.png',fullPage:true});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Overflow móvil');
  await page.locator('#search').fill('zzzzunfindable');
  await page.locator('#search-button').click();
  await page.waitForFunction(()=>!document.body.classList.contains('loading'));
  if(!await page.locator('#empty').isVisible())throw Error('Falta estado vacío');
  if(errors.length)throw Error(errors.join('\n'));
  fs.writeFileSync('benchmarks/p2/results/frontend_validation.json',JSON.stringify({catalog:true,text:true,ivf:true,bovw:true,exact:true,image_upload:true,map:true,geographic_knn:true,sql:true,experiments:4,mobile_width:390,empty_state:true,console_errors:errors},null,2));
  await browser.close();console.log('E2E multimodal OK');
})().catch(e=>{console.error(e);process.exit(1)});
